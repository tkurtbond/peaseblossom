#!/usr/bin/env python3
# Regenerates digits.mod and expected (not run by the test). Out.LongReal and
# Out.Real print the correctly rounded digits of the exact value; Python's %e
# (the C library's printf, correctly rounded, ties to even on exact ties) is
# the oracle. For each value and field width n the layout is Out's: d digits
# generated (d = max(dr, 15) for a LONGREAL, max(dr, 6) for a REAL, dr = n - 6
# or n - 5 capped at 17 or 9), then trailing zeros dropped while d > max(dr,
# 2). Leading blanks are stripped from both sides (the field width is Out's
# own, tested elsewhere). Run: python3 generate.py
import random, struct
random.seed(20260920)

def literal(v, single=False):
    if single:
        t = '%.9g' % v
        m, _, e = t.partition('e')
        if '.' not in m: m += '.0'
        return m + 'E' + (e.lstrip('+') if e else '0')
    t = repr(v)
    m, _, e = t.partition('e')
    if '.' not in m: m += '.0'
    return m + 'D' + (e.lstrip('+') if e else '0')

def fmt(v, n, long):
    neg = str(v).startswith('-') or (v == 0 and struct.pack('>d', v)[0] & 0x80)
    if neg: n -= 1
    dr = n - (6 if long else 5)
    dr = min(dr, 17 if long else 9)
    d = max(dr, 15 if long else 6)
    if v == 0:
        digits = '0' * d; e10 = 0
    else:
        t = '%.*e' % (d - 1, abs(v))
        m, _, e = t.partition('e')
        digits = m.replace('.', ''); e10 = int(e)
    dr = max(dr, 2)
    while d > dr and digits.endswith('0') and len(digits) > 1:
        digits = digits[:-1]; d -= 1
    if len(digits) < 2: digits += '0'
    ex = ('%+04d' if long else '%+03d') % e10 if v != 0 else ('+000' if long else '+00')
    return ('-' if neg else '') + digits[0] + '.' + digits[1:] + ('D' if long else 'E') + ex

longs = [0.1, 0.2, 0.3, 1.0, 1.5, 3.14159265358979, 123.456, 1e22, 1e23, 8.41e21,
         5e-324, 1e-323, 2.2250738585072014e-308, 2.2250738585072009e-308,
         1.7976931348623157e308, 2.0**-24, 2.0**-20, 2.0**-30, 2.0**60, 2.0**100,
         0.5, 0.125, 9007199254740993.0, 1e15, 1e16, 1e17, 999999999999999.9,
         9.999999999999999e22, 0.99999999999999999, 1e-5, 0.0, -0.0, -1.5, -1e300,
         5.9604644775390625e-08, 4.35, 100.0, 1e100, 1e-100, 12345.678901234567]
for _ in range(120):
    bits = random.getrandbits(64)
    v = struct.unpack('>d', struct.pack('>Q', bits))[0]
    if v != v or abs(v) == float('inf'): continue
    longs.append(v)
singles = [0.1, 0.5, 1.0, 3.0e38, 1.0e-45, 1.17549435e-38, 16777217.0, 123.456, -2.5, 0.0]
for _ in range(60):
    bits = random.getrandbits(32)
    v = struct.unpack('>f', struct.pack('>I', bits))[0]
    if v != v or abs(v) == float('inf'): continue
    singles.append(v)
widths_long = [24, 22, 21, 10, 0]
widths_short = [14, 12, 8, 0]
out = ['MODULE digits;',
       '  (* Phase 11 step 2 (inventory A3): Out.LongReal / Out.Real print the',
       '     correctly rounded digits. Generated by generate.py; see the header there. *)',
       '  IMPORT Out;', '  PROCEDURE L(x: LONGREAL; n: INTEGER); BEGIN Out.LongReal(x, n); Out.Ln END L;',
       '  PROCEDURE S(x: REAL; n: INTEGER); BEGIN Out.Real(x, n); Out.Ln END S;', 'BEGIN']
exp = []
for v in longs:
    for n in widths_long:
        out.append('  L(%s, %d);' % (literal(v), n)); exp.append(fmt(v, n, True))
for v in singles:
    vs = struct.unpack('>f', struct.pack('>f', v))[0]
    for n in widths_short:
        out.append('  S(%s, %d);' % (literal(vs, True), n)); exp.append(fmt(vs, n, False))
out.append('END digits.')
open('digits.mod', 'w').write('\n'.join(out) + '\n')
open('expected', 'w').write('\n'.join(exp) + '\n')
print(len(exp), 'lines')

# PLAN.md Phase 17 step 3 (doc/developer/vax-macro32-backend.md, section
# 19.7, proposal 6): the same for the VAX, ../vax-real-digits/digits.mod
# and its guest-run.expected. A LONGREAL is G_floating and a REAL
# F_floating there (section 14, item 9): no -0, no subnormals, and other
# ranges. The values above that are normal in both formats keep their
# oracle, %e of the same double: 2^-1022 to just under 2^1023 for a
# LONGREAL, 2^-126 to just under 2^127 for a REAL, and 0: poc spells a
# numeral that MACRO would round away from zero, exactly halfway, so that
# MACRO makes the front end's value of it, rounded to even (Phase 18 step
# 6d, doc/developer/vax-object-language.md, section 17.6), and poc's
# objects make that value too. The values only
# the VAX has - its smallest and largest of each type, and a few between
# the smallest and IEEE's smallest normal - get their digits from exact
# fractions, rounded to nearest, ties to even, as RealDigits rounds, and
# are written as the shortest numeral that rounds to them at the VAX's
# precision, which MACRO converts exactly. The guest's output is compared
# whole, so each line keeps the blanks that fill its field.
from fractions import Fraction as Q

def vax_round(x, p):
    # x rounded to p significant bits, ties to even
    e = x.numerator.bit_length() - x.denominator.bit_length() - p
    while x / Q(2) ** e >= 2 ** p: e += 1
    while x / Q(2) ** e < 2 ** (p - 1): e -= 1
    q = x / Q(2) ** e; n = int(q); r = q - n
    if r > Q(1, 2) or (r == Q(1, 2) and n % 2): n += 1
    return Q(n) * Q(2) ** e

def vax_value(numeral, p):
    # what poc makes of a numeral on the VAX: the nearest value, ties to
    # even, so that 1.0D23 and 8.41D21, exactly halfway between two
    # doubles, are the lower one, as IEEE's are (MACRO itself rounds ties
    # away from zero, MACRO 9.2.8.3, and poc spells those two otherwise)
    x = Q(numeral.replace('D', 'E'))
    if x == 0: return x
    sign = -1 if x < 0 else 1
    return sign * vax_round(abs(x), p)

def decimal_digits(x, d):
    # the d significant digits of x > 0, rounded to nearest, ties to even,
    # and its decimal exponent
    e10 = len(str(x.numerator // x.denominator)) - 1 if x >= 1 else -len(str(x.denominator // x.numerator))
    while x >= Q(10) ** (e10 + 1): e10 += 1
    while x < Q(10) ** e10: e10 -= 1
    q = x / Q(10) ** (e10 - d + 1); n = int(q); r = q - n
    if r > Q(1, 2) or (r == Q(1, 2) and n % 2): n += 1
    if n == 10 ** d: n //= 10; e10 += 1
    return str(n), e10

def shortest(x, p, letter):
    # the shortest numeral that rounds to x at p bits
    for d in range(1, 30):
        digits, e10 = decimal_digits(x, d)
        if vax_round(Q(int(digits)) * Q(10) ** (e10 - d + 1), p) == x:
            m = digits[0] + '.' + (digits[1:] or '0')
            return m + letter + str(e10)

def fmt_exact(x, n, long):
    # fmt for an exact fraction, not -0
    if x == 0: return fmt(0.0, n, long)
    neg = x < 0
    x = abs(x)
    if neg: n -= 1
    dr = n - (6 if long else 5)
    dr = min(dr, 17 if long else 9)
    d = max(dr, 15 if long else 6)
    digits, e10 = decimal_digits(x, d)
    dr = max(dr, 2)
    while d > dr and digits.endswith('0') and len(digits) > 1:
        digits = digits[:-1]; d -= 1
    if len(digits) < 2: digits += '0'
    ex = ('%+04d' if long else '%+03d') % e10
    return ('-' if neg else '') + digits[0] + '.' + digits[1:] + ('D' if long else 'E') + ex

def normal_in_both(v, low, high):
    return v == 0 and str(v)[0] != '-' or low <= abs(v) < high

vout = ['MODULE digits;',
        '  (* Phase 17 step 3 (doc/developer/vax-macro32-backend.md, section 19.7,',
        '     proposal 6): llvm-real-digits\' digits.mod for the VAX. Generated by',
        '     ../llvm-real-digits/generate.py; see the header there. *)',
        '  IMPORT Out;', '  PROCEDURE L(x: LONGREAL; n: INTEGER); BEGIN Out.LongReal(x, n); Out.Ln END L;',
        '  PROCEDURE S(x: REAL; n: INTEGER); BEGIN Out.Real(x, n); Out.Ln END S;', 'BEGIN']
vexp = []
for v in longs:
    if normal_in_both(v, 2.0 ** -1022, 2.0 ** 1023):
        for n in widths_long:
            vout.append('  L(%s, %d);' % (literal(v), n))
            vexp.append(fmt_exact(vax_value(literal(v), 53), n, True).rjust(n))
vax_longs = [Q(2) ** -1024, (1 + Q(2) ** -52) * Q(2) ** -1024, Q(3, 2) * Q(2) ** -1023,
             Q(2 ** 53 - 1) * Q(2) ** -1075, Q(2 ** 53 - 1) * Q(2) ** 970]
for x in vax_longs:
    for n in widths_long:
        vout.append('  L(%s, %d);' % (shortest(x, 53, 'D'), n)); vexp.append(fmt_exact(x, n, True).rjust(n))
for v in singles:
    vs = struct.unpack('>f', struct.pack('>f', v))[0]
    if normal_in_both(vs, 2.0 ** -126, 2.0 ** 127):
        for n in widths_short:
            vout.append('  S(%s, %d);' % (literal(vs, True), n))
            vexp.append(fmt_exact(vax_value(literal(vs, True), 24), n, False).rjust(n))
vax_singles = [Q(2) ** -128, Q(3, 2) * Q(2) ** -128, Q(2 ** 24 - 1) * Q(2) ** -151,
               Q(2 ** 24 - 1) * Q(2) ** 103]
for x in vax_singles:
    for n in widths_short:
        vout.append('  S(%s, %d);' % (shortest(x, 24, 'E'), n)); vexp.append(fmt_exact(x, n, False).rjust(n))
vout.append('END digits.')
open('../vax-real-digits/digits.mod', 'w').write('\n'.join(vout) + '\n')
open('../vax-real-digits/guest-run.expected', 'w').write(
    'build status: %X10000001\n' + '\n'.join(vexp) + '\nrun status: %X00000001\n')
print(len(vexp), 'lines for the VAX')
